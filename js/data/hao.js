/** 6 位代码 → 带市场前缀的 id（名单全为主板，6 开头沪市、0 开头深市） */
export function haoId(code) {
  const c = String(code || '').trim();
  if (/^6/.test(c)) return 'sh' + c;
  if (/^0/.test(c)) return 'sz' + c;
  return 'sh' + c;
}

