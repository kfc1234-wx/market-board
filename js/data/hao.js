/** @type {Array<{id:string, code:string, name:string}>} */
export const HAO_LIST = (() => {
  const seen = new Set();
  const out = [];
  for (const [code, name] of RAW) {
    const id = haoId(code);
    if (seen.has(id)) continue;
    seen.add(id);
    out.push({ id, code, name });
  }
  return out;
})();

export const HAO_COUNT = HAO_LIST.length;

export const HAO_IDS = HAO_LIST.map(x => x.id);
