/** @type {Array<{id:string, code:string, name:string, group:string, industry:string, track:string, type:string}>} */
export const HAO_LIST = (() => {
  const seen = new Set();
  const out = [];
  for (const [code, name, group, industry, track] of RAW) {
    const id = haoId(code);
    if (seen.has(id)) continue;
    seen.add(id);
    out.push({ id, code, name, group, industry, track, type: `${group}-${industry}-${track}` });
  }
  return out;
})();

export const HAO_COUNT = HAO_LIST.length;

export const HAO_IDS = HAO_LIST.map(x => x.id);
